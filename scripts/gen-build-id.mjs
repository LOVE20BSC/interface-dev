#!/usr/bin/env node
// Writes a tiny build-id module plus the id used by the post-build step.
// The id is regenerated for every build and compared at runtime with
// dist/build-id.json to detect a stale HTML shell (GitHub Pages caches it).
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// `pnpm e2e` sets E2E_BUILD_ID to a fingerprint of the sources + build environment so the preview
// guard can tell a current bundle from a stale one (see playwright.config.ts). Every other build
// keeps the timestamp-random id.
const override = (process.env.E2E_BUILD_ID ?? '').trim();
const id = /^[a-z0-9][a-z0-9-]{0,63}$/.test(override)
  ? override
  : `${Date.now().toString(36)}-${randomBytes(4).toString('hex')}`;
const target = resolve(root, 'src/config/build-id.generated.ts');

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/gen-build-id.mjs. Do not edit, do not commit.\nexport const BUILD_ID = ${JSON.stringify(id)} as const;\n`,
  'utf8',
);
writeFileSync(resolve(root, '.build-id'), id, 'utf8');
console.log(`[build-id] ${id}`);
