#!/usr/bin/env node
// Generates src/config/errors.generated.ts from the protocol error registry.
//
// Source (read-only, sibling repo): matt-gov/registry/errors.json
// The output is committed: a clean frontend checkout has no registry.
// If the registry is missing we fall back to a tiny hand-written map and mark it
// with TODO: regenerate, so the UI never shows raw revert data.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const registryPath =
  process.env.LOVE20_ERRORS_JSON ?? resolve(root, '../matt-gov/registry/errors.json');
const messagesPath = resolve(root, 'scripts/error-messages.zh.json');
const outputPath = resolve(root, 'src/config/errors.generated.ts');

const FALLBACK = [
  {
    selector: '0xea74f32b',
    signature: 'RoundNotStarted(uint256,uint256)',
    name: 'RoundNotStarted',
    message: '这一轮还没有开始，请稍后再来。',
  },
  {
    selector: '0x33393244',
    signature: 'NotMemberOwner(uint256)',
    name: 'NotMemberOwner',
    message: '这个身份不属于当前钱包，请切换到正确的钱包或身份。',
  },
  {
    selector: '0xc7a2002f',
    signature: 'InvalidKeyOrder(uint256,uint256)',
    name: 'InvalidKeyOrder',
    message: '参数顺序不正确，请联系管理员。',
  },
  {
    selector: '0x08c379a0',
    signature: 'Error(string)',
    name: 'Error',
    message: '操作没有完成，请检查输入后重试。',
  },
];

const messages = JSON.parse(readFileSync(messagesPath, 'utf8'));

let entries;
let sourceKind;
if (existsSync(registryPath)) {
  const raw = readFileSync(registryPath, 'utf8');
  const parsed = JSON.parse(raw);
  if (!Array.isArray(parsed.errors)) {
    throw new Error(`[errors] ${registryPath} has no "errors" array`);
  }
  sourceKind = 'registry';
  const missing = new Set();
  entries = parsed.errors.map((error) => {
    const name = error.signature.replace(/\(.*$/, '');
    const message = messages[name];
    if (!message) missing.add(name);
    return {
      selector: error.selector.toLowerCase(),
      signature: error.signature,
      name,
      message: message ?? '操作没有完成，请稍后重试。',
    };
  });
  if (missing.size > 0) {
    throw new Error(
      `[errors] missing Chinese copy for ${missing.size} error name(s): ${[...missing].join(', ')}\nAdd them to scripts/error-messages.zh.json.`,
    );
  }
  const hash = createHash('sha256').update(raw).digest('hex').slice(0, 16);
  sourceKind = `registry@sha256:${hash}`;
} else {
  console.warn(`[errors] registry not found at ${registryPath}; writing fallback map.`);
  sourceKind = 'fallback-hand-written';
  entries = FALLBACK;
}

// The registry lists shared errors once per declaring repo, so the same
// selector can appear several times. A selector map must have one entry each.
const bySelector = new Map();
for (const entry of entries) {
  if (!bySelector.has(entry.selector)) bySelector.set(entry.selector, entry);
}
entries = [...bySelector.values()];
entries.sort((a, b) => a.selector.localeCompare(b.selector));

const lines = [];
lines.push('// AUTO-GENERATED by scripts/gen-errors.mjs. Do not edit by hand.');
lines.push('// Regenerate with: pnpm gen:errors');
lines.push(`// Source: ${sourceKind}`);
lines.push('//');
lines.push('// Selector -> Chinese sentence. This is the only user-facing rendering of a');
lines.push('// contract custom error; raw revert data must never reach the screen.');
if (sourceKind === 'fallback-hand-written') {
  lines.push('// TODO: regenerate from matt-gov/registry/errors.json (currently unavailable).');
}
lines.push('');
lines.push('export type ContractErrorSelector = `0x${string}`;');
lines.push('');
lines.push('export interface ContractErrorCatalogEntry {');
lines.push('  readonly selector: ContractErrorSelector;');
lines.push('  readonly signature: string;');
lines.push('  readonly name: string;');
lines.push('  readonly message: string;');
lines.push('}');
lines.push('');
lines.push('export const CONTRACT_ERROR_CATALOG: readonly ContractErrorCatalogEntry[] = [');
for (const entry of entries) {
  lines.push(
    `  { selector: ${JSON.stringify(entry.selector)}, signature: ${JSON.stringify(entry.signature)}, name: ${JSON.stringify(entry.name)}, message: ${JSON.stringify(entry.message)} },`,
  );
}
lines.push('];');
lines.push('');
lines.push('export const CONTRACT_ERROR_MESSAGES: Readonly<Record<string, string>> =');
lines.push('  Object.freeze({');
for (const entry of entries) {
  lines.push(`    ${JSON.stringify(entry.selector)}: ${JSON.stringify(entry.message)},`);
}
lines.push('  });');
lines.push('');
lines.push('export const CONTRACT_ERROR_NAMES: Readonly<Record<string, string>> =');
lines.push('  Object.freeze({');
for (const entry of entries) {
  lines.push(`    ${JSON.stringify(entry.selector)}: ${JSON.stringify(entry.name)},`);
}
lines.push('  });');
lines.push('');
lines.push(`export const ERROR_REGISTRY_SOURCE = ${JSON.stringify(sourceKind)};`);
lines.push('');

writeFileSync(outputPath, lines.join('\n'), 'utf8');
console.log(
  `[errors] wrote ${entries.length} selector(s) to src/config/errors.generated.ts (${sourceKind})`,
);
